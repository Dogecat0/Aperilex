#!/usr/bin/env bash
#
# Stage 5 identity backfill helper.
#
# This script maps the legacy mock user UUID that currently exists on task and analysis
# records to a newly provisioned real user created during the Stage 5 migrations.
#
# Requirements:
#   * Stage 5 identity migrations (users, user_identities, user_profiles) applied
#   * Docker services running (`docker compose up -d postgres app`)
#   * Provide NEW_USER_ID, NEW_USER_EMAIL, and PROVIDER_SUBJECT environment variables
#     before invoking this script. Optional overrides documented below.
#
# Example usage:
#   NEW_USER_ID=11111111-2222-3333-4444-555555555555 \
#   NEW_USER_EMAIL=founder@aperilex.com \
#   PROVIDER_SUBJECT=google-oauth2|123456789012345678901 \
#   ./scripts/backfill_stage5_identity.sh
#
# Optional environment variables:
#   USER_TIER (default: BASIC)
#   USER_STATUS (default: ACTIVE)
#   USER_IDENTITY_ID (autogenerated if empty)
#   USER_PROFILE_ID (autogenerated if empty)
#   PROVIDER (default: GOOGLE)
#   PROVIDER_EMAIL (default: NEW_USER_EMAIL)
#
set -euo pipefail

LEGACY_USER_ID="00000000-0000-0000-0000-000000000000"

: "${NEW_USER_ID:?Set NEW_USER_ID to the UUID that will backfill legacy rows}"
: "${NEW_USER_EMAIL:?Set NEW_USER_EMAIL to the email for the real user record}"
: "${PROVIDER_SUBJECT:?Set PROVIDER_SUBJECT to the upstream identity subject (e.g., Google sub)}"

USER_TIER=${USER_TIER:-BASIC}
USER_STATUS=${USER_STATUS:-ACTIVE}
PROVIDER=${PROVIDER:-GOOGLE}
PROVIDER_EMAIL=${PROVIDER_EMAIL:-$NEW_USER_EMAIL}
USER_IDENTITY_ID=${USER_IDENTITY_ID:-$(uuidgen)}
USER_PROFILE_ID=${USER_PROFILE_ID:-$(uuidgen)}
SCHEMA_VERSION=${SCHEMA_VERSION:-1}

read -r -d '' SQL <<SQL_EOF
BEGIN;

-- Ensure base user exists prior to backfill updates.
INSERT INTO users (id, schema_version, email, status, tier, created_at, updated_at)
VALUES ('${NEW_USER_ID}', ${SCHEMA_VERSION}, '${NEW_USER_EMAIL}', '${USER_STATUS}', '${USER_TIER}', now(), now())
ON CONFLICT (id) DO UPDATE
SET email = EXCLUDED.email,
    status = EXCLUDED.status,
    tier = EXCLUDED.tier,
    updated_at = now();

-- Wire the external identity record.
INSERT INTO user_identities (
    id,
    schema_version,
    user_id,
    provider,
    provider_subject,
    provider_email,
    raw_profile,
    verified_at,
    created_at,
    updated_at
) VALUES (
    '${USER_IDENTITY_ID}',
    ${SCHEMA_VERSION},
    '${NEW_USER_ID}',
    '${PROVIDER}',
    '${PROVIDER_SUBJECT}',
    '${PROVIDER_EMAIL}',
    '{}',
    now(),
    now(),
    now()
) ON CONFLICT (user_id, provider, provider_subject)
DO UPDATE SET provider_email = EXCLUDED.provider_email,
              raw_profile = EXCLUDED.raw_profile,
              verified_at = COALESCE(EXCLUDED.verified_at, user_identities.verified_at),
              updated_at = now();

-- Ensure a profile shell exists.
INSERT INTO user_profiles (
    id,
    schema_version,
    user_id,
    display_name,
    avatar_url,
    preferences,
    time_zone,
    created_at,
    updated_at
) VALUES (
    '${USER_PROFILE_ID}',
    ${SCHEMA_VERSION},
    '${NEW_USER_ID}',
    NULL,
    NULL,
    '{}'::json,
    NULL,
    now(),
    now()
) ON CONFLICT (user_id)
DO UPDATE SET updated_at = now();

-- Backfill analyses -> users linkage when legacy sentinel UUID is present.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'public' AND table_name = 'analyses'
    ) THEN
        UPDATE analyses
        SET user_id = '${NEW_USER_ID}'
        WHERE user_id = '${LEGACY_USER_ID}'
           OR user_id IS NULL;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'public' AND table_name = 'tasks'
    ) THEN
        UPDATE tasks
        SET user_id = '${NEW_USER_ID}'
        WHERE user_id = '${LEGACY_USER_ID}'
           OR user_id IS NULL;
    END IF;
END $$;

COMMIT;
SQL_EOF

printf '%s
' "Planned SQL:" >&2
printf '%s
' "$SQL" >&2
printf '%s
' "---" >&2
printf '%s
' "The SQL above has NOT been executed. Review and run manually when Stage 5 migrations land." >&2

