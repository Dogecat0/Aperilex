#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import vm from 'node:vm'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const repoRoot = path.resolve(__dirname, '..')

const tokensPath = path.resolve(repoRoot, 'frontend/src/styles/tokens.ts')
const generatedCssPath = path.resolve(repoRoot, 'frontend/src/styles/generated-theme.css')
const generatedJsonPath = path.resolve(repoRoot, 'frontend/tailwind.design-tokens.json')

const headerComment = `/*
 * Auto-generated by scripts/generate-design-tokens.mjs
 * Do not edit directly. Update frontend/src/styles/tokens.ts instead.
 */\n\n`

function toKebabCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/_/g, '-')
    .toLowerCase()
}

function flattenTokenObject(tokenObject, options = {}) {
  const { prefix = [], skipKeys = new Set(['name']) } = options
  const entries = []

  const walk = (value, pathParts) => {
    if (value === null || value === undefined) {
      return
    }

    if (Array.isArray(value)) {
      value.forEach((nestedValue, index) => {
        walk(nestedValue, [...pathParts, String(index)])
      })
      return
    }

    if (typeof value === 'object') {
      for (const [key, nestedValue] of Object.entries(value)) {
        if (skipKeys.has(key)) {
          continue
        }
        walk(nestedValue, [...pathParts, key])
      }
      return
    }

    if (typeof value === 'string' || typeof value === 'number') {
      const cssVariableName = `--${pathParts.map(toKebabCase).join('-')}`
      entries.push([cssVariableName, String(value)])
    }
  }

  walk(tokenObject, prefix)
  return entries
}

let cachedTsModule = null

async function getTypeScriptModule() {
  if (cachedTsModule) {
    return cachedTsModule
  }

  const tsPath = path.resolve(repoRoot, 'frontend/node_modules/typescript/lib/typescript.js')
  const moduleUrl = pathToFileURL(tsPath).href
  const imported = await import(moduleUrl)
  cachedTsModule = imported.default ?? imported
  return cachedTsModule
}

async function loadTokens() {
  const ts = await getTypeScriptModule()
  const source = await readFile(tokensPath, 'utf8')
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2019,
      esModuleInterop: true,
    },
    fileName: tokensPath,
  })

  const sandbox = {
    module: { exports: {} },
    exports: null,
    require: (specifier) => {
      throw new Error(`Dynamic require not supported in token loader: ${specifier}`)
    },
  }
  sandbox.exports = sandbox.module.exports

  vm.runInNewContext(transpiled.outputText, sandbox, { filename: tokensPath })

  const moduleExports = sandbox.module.exports ?? {}
  const { lightTokens, darkTokens } = moduleExports

  if (!lightTokens || !darkTokens) {
    throw new Error('Expected lightTokens and darkTokens exports from tokens.ts')
  }

  return { lightTokens, darkTokens }
}

function buildThemeEntries(tokens) {
  const entries = []

  const simpleGroups = [
    ['brand', 'brand'],
    ['learning', 'learning'],
    ['action', 'action'],
    ['surfaces', 'surfaces'],
    ['text', 'text'],
    ['lines', 'lines'],
    ['status', 'status'],
    ['metrics', 'metrics'],
    ['focus', 'focus'],
    ['spacing', 'spacing'],
    ['shadows', 'shadow'],
  ]

  for (const [groupKey, prefix] of simpleGroups) {
    const group = tokens[groupKey] ?? {}
    for (const [key, value] of Object.entries(group)) {
      entries.push([`--${prefix}-${toKebabCase(key)}`, value])
    }
  }

  if (tokens.data) {
    for (const [key, value] of Object.entries(tokens.data)) {
      if (Array.isArray(value)) {
        value.forEach((item, index) => {
          entries.push([`--data-${toKebabCase(key)}-${index}`, item])
        })
      } else {
        entries.push([`--data-${toKebabCase(key)}`, value])
      }
    }
  }

  if (tokens.typography) {
    const { sans, serif, mono, weights, lineHeights, letterSpacing } = tokens.typography
    if (sans) entries.push(['--font-family-sans', sans])
    if (serif) entries.push(['--font-family-serif', serif])
    if (mono) entries.push(['--font-family-mono', mono])

    for (const [key, value] of Object.entries(weights ?? {})) {
      entries.push([`--font-weight-${toKebabCase(key)}`, String(value)])
    }

    for (const [key, value] of Object.entries(lineHeights ?? {})) {
      entries.push([`--line-height-${toKebabCase(key)}`, String(value)])
    }

    for (const [key, value] of Object.entries(letterSpacing ?? {})) {
      entries.push([`--letter-spacing-${toKebabCase(key)}`, value])
    }
  }

  return entries
}

function buildCss(lightTokens, darkTokens) {
  const lightEntries = flattenTokenObject(lightTokens)
  const darkEntries = flattenTokenObject(darkTokens)

  const formatBlock = (selector, entries) => {
    const body = entries
      .map(([name, value]) => `  ${name}: ${value};`)
      .join('\n')
    return `${selector} {\n${body}\n}\n`
  }

  const themeEntries = buildThemeEntries(lightTokens)
  const themeBlock = `@theme {\n${themeEntries
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n')}\n}\n\n`

  const css = [
    headerComment,
    themeBlock,
    formatBlock(':root, :root[data-theme="light"]', lightEntries),
    '\n',
    formatBlock(':root[data-theme="dark"]', darkEntries),
  ].join('')

  return css
}

async function writeOutputs(lightTokens, darkTokens) {
  const css = buildCss(lightTokens, darkTokens)
  let existingCss = null
  try {
    existingCss = await readFile(generatedCssPath, 'utf8')
  } catch (error) {
    if (error?.code !== 'ENOENT') {
      throw error
    }
  }
  if (existingCss !== css) {
    await writeFile(generatedCssPath, css, 'utf8')
  }

  const jsonBase = {
    generator: path.relative(repoRoot, __filename),
    notice:
      'Auto-generated. Do not edit directly. Update frontend/src/styles/tokens.ts instead.',
    source: path.relative(repoRoot, tokensPath),
    tokens: {
      light: lightTokens,
      dark: darkTokens,
    },
  }

  let existingJson = null
  try {
    existingJson = JSON.parse(await readFile(generatedJsonPath, 'utf8'))
  } catch (error) {
    if (error?.code !== 'ENOENT') {
      existingJson = null
    }
  }

  const existingBase =
    existingJson && typeof existingJson === 'object'
      ? {
          generator: existingJson.generator,
          notice: existingJson.notice,
          source: existingJson.source,
          tokens: existingJson.tokens,
        }
      : null

  if (existingBase && JSON.stringify(existingBase) === JSON.stringify(jsonBase)) {
    return
  }

  const jsonPayload = {
    generatedAt: new Date().toISOString(),
    ...jsonBase,
  }

  await writeFile(generatedJsonPath, `${JSON.stringify(jsonPayload, null, 2)}\n`, 'utf8')
}

async function main() {
  try {
    const { lightTokens, darkTokens } = await loadTokens()
    await writeOutputs(lightTokens, darkTokens)
    console.log(`Generated CSS → ${path.relative(repoRoot, generatedCssPath)}`)
    console.log(`Generated JSON → ${path.relative(repoRoot, generatedJsonPath)}`)
  } catch (error) {
    console.error('Error generating design tokens:')
    console.error(error)
    process.exitCode = 1
  }
}

await main()
